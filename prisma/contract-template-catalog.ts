function seed(
  code: string,
  sourceName: string,
  lines: string[],
  sourceUrl?: string,
): ContractTemplateBodySeed {
  return {
    code,
    sourceName,
    sourceUrl,
    copiedVerbatimFromMySpider: false,
    fields: {
      bodyText: lines.join('\n'),
      legalBasisText: sourceName,
      sourceNotice: SOURCE_NOTICE,
    },
  };
}

function mergeTemplateMetadata(
  metadata: unknown,
  seed: ContractTemplateBodySeed,
): Record<string, unknown> {
  const current = asRecord(metadata);
  const documentEngine = asRecord(current.documentEngine);
  const fields = asRecord(documentEngine.fields);
  const fieldGroups = CONTRACT_TEMPLATE_FIELD_GROUPS[seed.code];
  const defaultBody = CONTRACT_TEMPLATE_BODY_CLAUSES[seed.code];

  return {
    ...current,
    sourceName: seed.sourceName,
    sourceUrl: seed.sourceUrl ?? current.sourceUrl,
    copiedVerbatimFromMySpider: seed.copiedVerbatimFromMySpider,
    mySpiderReference: {
      ...asRecord(current.mySpiderReference),
      ...MYSPIDER_REFERENCE,
    },
    documentEngine: {
      ...documentEngine,
      version: 1,
      fields: {
        ...fields,
        ...seed.fields,
      },
      ...(fieldGroups
        ? {
            fieldGroups,
            amountUnit: 'manwon',
            amountUnitNote: AMOUNT_UNIT_NOTE,
          }
        : {}),
      // 거래유형별 기본 본문 조항 (레거시 DMSV001Q03) — 엔진이 신규 문서에 주입
      ...(defaultBody ? { defaultBody } : {}),
    },
  };
}

function asRecord(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}
